-- 本地服安全守卫：二周年抽奖 VO 兜底
-- 客户端刚进主城时如果用户立即点击二周年抽奖，可能在协议到达前触发 countDown/onGUI，
-- 导致 ActivityMgr.getTwoAnnLuckyDrawVO() 为 nil 进而崩溃。
-- 这里包装 getTwoAnnLuckyDrawVO：若为 nil，自动从配置表预先构建当天的默认 VO 返回，绝不返回 nil！
if type(ActivityMgr) == "table" and type(ActivityMgr.getTwoAnnLuckyDrawVO) == "function" then
	local _psOrigGetTwoAnnVO = ActivityMgr.getTwoAnnLuckyDrawVO
	function ActivityMgr.getTwoAnnLuckyDrawVO()
		local name, val = debug.getupvalue(_psOrigGetTwoAnnVO, 1)
		if val ~= nil then
			return val
		end
		local curDay = (ActivityMgr.getCurrentDay and ActivityMgr.getCurrentDay()) or 1
		if ActivityConfig and ActivityConfig.getActivityTwoAnnLuDrawVO then
			val = ActivityConfig.getActivityTwoAnnLuDrawVO(curDay)
			if val ~= nil then
				pcall(debug.setupvalue, _psOrigGetTwoAnnVO, 1, val)
			end
		end
		return val
	end
	print("PS-TWOANN-GUARD-INSTALLED")
end
