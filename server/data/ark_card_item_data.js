function isCardItem(typeId) {
  const t = Number(typeId);
  return !!(SINGLE[t] || PACKS[t]);
}

// 一次"使用 1 个"的产出（随机包每次重掷；固定包返回副本，调用方可安全 push）
function cardsOfItem(typeId) {
  const t = Number(typeId);
  if (SINGLE[t]) return [SINGLE[t]];
  const p = PACKS[t];
  if (!p) return [];
  if (p.cards) return p.cards.slice();
  const pool = p.pool.slice();
  const out = [];
  for (let i = 0; i < (p.pick || 1) && pool.length; i++) {
    out.push(pool.splice(Math.floor(Math.random() * pool.length), 1)[0]);
  }
  return out;
}

function maxUseOf(typeId) {
  return MAX_USE[Number(typeId)] || 10;
}

// 这个道具**可能**开出的全部卡（随机包返回整个池，不掷骰）——用于"是否已全部拥有"判定
function potentialCards(typeId) {
  const t = Number(typeId);
  if (SINGLE[t]) return [SINGLE[t]];
  const p = PACKS[t];
  if (!p) return [];
  return p.cards ? p.cards.slice() : p.pool.slice();
}

