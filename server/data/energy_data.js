// 喂养一只 type 的誓灵对各属性上限的增量：{prop: delta}（prop=0 展开到全 6 属性）
function feedGainOf(type) {
  const e = SERVANT_ENERGY[type];
  if (!e) return {};
  const [point, prop] = e;
  if (prop === 0) return ENERGY_PROPS.reduce((o, p) => (o[p] = point, o), {});
  return { [prop]: point };
}

// 点数→属性加成（客户端 realcalcPropVal 同公式；prop 1=生命 0.2 系数，其余 0.1）
function energyPropBonus(prop, point, level) {
  const k = prop === 1 ? 0.2 : 0.1;
  return Math.ceil(Math.max(point * level * k, point));
}

// 全属性加成 {hp, phy_atk, mag_atk, phy_def, mag_def, speed}（战斗与面板口径一致）
function energyBonusOf(servant) {
  const pts = servant.energy_points || {};
  const lv = Number(servant.level) || 1;
  return {
    hp: energyPropBonus(1, pts["1"] || pts[1] || 0, lv),
    phy_atk: energyPropBonus(2, pts["2"] || pts[2] || 0, lv),
    mag_atk: energyPropBonus(3, pts["3"] || pts[3] || 0, lv),
    phy_def: energyPropBonus(4, pts["4"] || pts[4] || 0, lv),
    mag_def: energyPropBonus(5, pts["5"] || pts[5] || 0, lv),
    speed: energyPropBonus(6, pts["6"] || pts[6] || 0, lv),
  };
}

// 已分配点数总和（池 32 校验用）
function energySum(servant) {
  const pts = servant.energy_points || {};
  return ENERGY_PROPS.reduce((n, p) => n + (pts[String(p)] || pts[p] || 0), 0);
}

// 协议下发字段：p_servant_detail.energy=[{prop_code,ceil}] / energy_points=[{id,val}]
function energyFieldsOf(b) {
  const ceils = b.energy_ceils || {};
  const pts = b.energy_points || {};
  return {
    energy: ENERGY_PROPS.map(p => ({ prop_code: p, ceil: ceils[String(p)] || ceils[p] || 0 })),
    energy_points: ENERGY_PROPS.filter(p => (pts[String(p)] || pts[p] || 0) > 0)
      .map(p => ({ id: p, val: pts[String(p)] || pts[p] })),
  };
}

