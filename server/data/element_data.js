const CRYSTAL_IDS = new Set(Object.keys(ITEM_TO_SERVANT).map(Number));

// 71 前缀 = 元素精灵本体（bag_type 9）；72 前缀 = 元素晶石（转化材料，也在 bag 9）
function isElementItem(typeId) { return String(Number(typeId) || 0).slice(0, 2) === '71'; }
function isCrystal(typeId) {
  const t = Number(typeId) || 0;
  return CRYSTAL_IDS.has(t) || String(t).slice(0, 2) === '72';
}

// 真实实例（level 缺失/越界一律按 1 处理：0 会让客户端 ElementMergeVO.getCurrLvStr
// 读 mergeArr[0]=nil 直接崩，这是 71000001 走通用堆叠发放时的既有雷）
function normLevel(lv) {
  const n = Math.floor(Number(lv) || 0);
  return n < 1 ? 1 : (n > MAX_LV ? MAX_LV : n);
}
function strengthenOf(lv) { return STRENGTHEN[normLevel(lv)] || STRENGTHEN[1]; }

