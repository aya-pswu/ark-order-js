function getSellPrice(typeId) {
  const tid = Number(typeId) || 0;
  if (CAN_SELL_PRICES[tid] != null) return CAN_SELL_PRICES[tid];
  const d78 = Math.floor(tid / 1000000) % 100;
  if (d78 >= 10 && d78 <= 18) {
    const lv = tid % 10;
    if (lv === 1) return 10;
    if (lv === 2) return 100;
    if (lv === 3) return 200;
    if (lv >= 4) return 500;
  }
  if (d78 === 19) {
    const color = (tid % 10) + 2;
    if (color === 2) return 5;
    if (color === 3) return 50;
    if (color === 4) return 100;
    if (color >= 5) return 250;
  }
  return 0;
}

function canSellItem(typeId) {
  const tid = Number(typeId) || 0;
  if (CAN_SELL_PRICES[tid] != null) return true;
  const d78 = Math.floor(tid / 1000000) % 100;
  return (d78 >= 10 && d78 <= 19);
}

