// BOSS 掉落稀有度抽取：UR 2% / SR 5% / R 10% / N 30%，其余不掉（无 UR 池的关卡自然不掉 UR）
function rollDropTier() {
  const r = Math.random() * 100;
  if (r < 2) return 'UR';
  if (r < 7) return 'SR';
  if (r < 17) return 'R';
  if (r < 47) return 'N';
  return null;
}



