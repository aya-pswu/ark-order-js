function pushServantsBrief(conn) {
  // 顺序关键：MainFunctionPanel.update 监听 SERVANTS_BRIEF_TOC 事件，brief 到达即触发 onChangeHelp；
  // 若组/helper 还未到（RoleMgr.updateHelpGroup 未执行），getGroupList() 为空 → getServant(nil) 崩。
  // 所以必须先推看板娘组（m_role_profile_helper_toc + m_role_profile_info_toc），最后推 brief。
  if (servants.length > 0) {
    pushHelperGroup(conn);
  }
  conn.sendToc('m_servants_brief_toc', {
    size: servantBagSize,
    servants: servants,
  });
}

// help_list 元素形状 p_helper_brief {id, gain_time, feeling}（getGroupList 取 .id）

// 看板娘组顺序：最后切换的看板娘放首位（客户端登录显示 groupList[MainMgr.helpIndex=1]，
// 即 help_list[1]；updateHelpGroup 也会把 RoleMgr.helper 设为首位 id）
function helperOrderIds() {
  // 默认组：helperIdList 为空时用全部誓灵（而非仅 servants[0]）——
  // 否则 lastHelper 永远排不进单元素列表，看板娘持久化失效
  let ids = helperIdList.length > 0
    ? helperIdList.filter(id => servants.some(s => s.id === id))
    : servants.map(s => s.id);
  const lh = helperState.lastHelper;
  if (lh && ids.includes(lh)) ids = [lh, ...ids.filter(i => i !== lh)];
  return ids;
}

function pushHelperGroup(conn) {
  const ids = helperOrderIds();
  const helpList = ids.map(id => {
    const s = servants.find(x => x.id === id);
    return { id: s.id, gain_time: s.gain_time, feeling: s.feeling };
  });
  conn.sendToc('m_role_profile_helper_toc', { help_list: helpList });
  // helper 字段 = 客户端 RoleMgr.helper（主页首显经补丁定位到它）——直接回最后切换的看板娘
  conn.sendToc('m_role_profile_info_toc', { intro: '', helper: helperState.lastHelper || ids[0] });
}

// GM 聊天指令（CfgDebug 定义，格式 m21_xxx=a=b），官方由服务端解释执行
function handleGmCommand(conn, msg) {
  const parts = (msg || '').split('=');
  const cmd = parts[0];
  if (cmd === 'm21_add_servant2' && parts.length >= 2) {
    // m21_add_servant2=<类型ID>=<数量>
    const type = parseInt(parts[1]);
    const count = Math.max(1, parseInt(parts[2]) || 1);
    if (!type) return false;
    for (let i = 0; i < count; i++) servants.push(makeServantBrief(type));
    log(`[GM] 添加誓灵 type=${type} x${count}，当前总数=${servants.length}`);
    saveState();
    pushServantsBrief(conn);
    return true;
  }
  if (cmd === 'm21_add_servant' && parts.length >= 2) {
    // m21_add_servant=<类型ID1>=<类型ID2>=... 每样一只
    let n = 0;
    for (const t of parts.slice(1)) {
      const type = parseInt(t);
      if (type) { servants.push(makeServantBrief(type)); n++; }
    }
    if (!n) return false;
    log(`[GM] 批量添加誓灵 ${n} 只，当前总数=${servants.length}`);
    saveState();
    pushServantsBrief(conn);
    return true;
  }
  if (cmd === 'm21_set_helper' && parts.length >= 2) {
    // m21_set_helper=<誓灵id>：主页切换按钮的通知（客户端补丁经聊天通道转发）
    const id = parseInt(parts[1]);
    if (id && servants.some(s => s.id === id)) {
      helperState.lastHelper = id;
      saveState();
      // 回 info_toc：解除 1 秒网络等待（checkSendBack）+ 更新 RoleMgr.helper（选择界面"当前"标记）
      conn.sendToc('m_role_profile_info_toc', { intro: '', helper: id });
      log(`[helper] 记录看板娘 id=${id}`);
    }
    return true;
  }
  if (cmd === 'm21_goods' && parts.length >= 3) {
    // m21_goods=<type_id>=<数量>[=<type_id>=<数量>...]（CfgDebug"获得道具"，支持多对连发）
    const changed = [];
    for (let i = 1; i + 1 < parts.length; i += 2) {
      const typeId = parseInt(parts[i]);
      const num = parseInt(parts[i + 1]);
      if (!typeId || !num) continue;
      if (VALID_ITEM_TYPES.size && !VALID_ITEM_TYPES.has(typeId)) {
        log(`[GM] 跳过未知物品 type_id=${typeId}（CfgItems 无此配置，下发会让客户端 getItemVO 崩）`);
        continue;
      }
      let g = bagGoods.find(x => x.type_id === typeId);
      if (g) g.cur_num += num;
      else { g = { id: nextGoodsId++, type_id: typeId, cur_num: num, bag_type: bagTypeOf(typeId) }; bagGoods.push(g); }
      changed.push(g);
    }
    if (changed.length) {
      saveState();
      pushGoodsUpdate(conn, changed, 3); // UPDATE：入包/改数（客户端 updateItem 不存在则 addItem）
      log(`[GM] 添加物品 ${changed.map(g => `${g.type_id}x${g.cur_num}`).join(' ')}，背包共 ${bagGoods.length} 类`);
    }
    return true;
  }
  if (cmd === 'm21_clear_bag') {
    if (bagGoods.length) {
      const removed = bagGoods.slice();
      bagGoods = [];
      saveState();
      pushGoodsUpdate(conn, removed, 2); // DEL：客户端 delGoods 移除
    }
    log('[GM] 清空背包');
    return true;
  }
  if (cmd === 'm21_bgold' && parts.length >= 2) {
    // 设置水晶（CfgDebug"设置水晶"）：gold=总量，gold_given=赠送部分（显示=两者之和，
    // 消耗客户端先扣赠送）——全额设为赠送
    roleAsset.gold = roleAsset.gold_given = Math.max(0, parseInt(parts[1]) || 0);
    saveState();
    pushAssetChange(conn);
    log(`[GM] 设置水晶 ${roleAsset.gold}`);
    return true;
  }
  if (cmd === 'm21_silver' && parts.length >= 2) {
    roleAsset.silver = Math.max(0, parseInt(parts[1]) || 0);
    saveState();
    pushAssetChange(conn);
    log(`[GM] 设置金币 ${roleAsset.silver}`);
    return true;
  }
  log('[GM] 未实现的指令:', msg);
  return false;
}

